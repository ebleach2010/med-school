function meta(id: string, sources: string[], review: ContentMeta["review"] = "pending"): ContentMeta {
  return { id, version: 1, provenance: "source-grounded", review, author: "ai-draft", sources, lastVerified: DATE };
}

function obj(prefix: string, list: [SkillId, string][]): Objective[] {
  return list.map(([skill, text], i) => ({ id: `${prefix}-o${i + 1}`, skill, text }));
}

