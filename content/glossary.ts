// Glossary of neurological terms. Lessons and items mark terms as [[term-id|shown text]].
// Each entry gives a plain-language meaning, the precise medical meaning, a simple
// pronunciation (stressed syllable in capitals) where useful, and a short clinical example.

import type { Term } from "../shared/types";

function t(
  id: string,
  term: string,
  aliases: string[],
  plain: string,
  medical: string,
  pronunciation: string | undefined,
  example: string,
  moduleId: string,
  related: string[],
): Term {
  const out: Term = { id, term, plain, medical, example, moduleId, related };
  if (aliases.length) out.aliases = aliases;
  if (pronunciation) out.pronunciation = pronunciation;
  return out;
}

